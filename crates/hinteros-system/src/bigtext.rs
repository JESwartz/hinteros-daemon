/// The base letter of a common accented Latin letter (é → e); anything else unchanged.
fn base_letter(c: char) -> char {
    match c {
        'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' => 'a',
        'À' | 'Á' | 'Â' | 'Ã' | 'Ä' | 'Å' => 'A',
        'ç' => 'c',
        'Ç' => 'C',
        'è' | 'é' | 'ê' | 'ë' => 'e',
        'È' | 'É' | 'Ê' | 'Ë' => 'E',
        'ì' | 'í' | 'î' | 'ï' => 'i',
        'Ì' | 'Í' | 'Î' | 'Ï' => 'I',
        'ñ' => 'n',
        'Ñ' => 'N',
        'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' => 'o',
        'Ò' | 'Ó' | 'Ô' | 'Õ' | 'Ö' | 'Ø' => 'O',
        'ù' | 'ú' | 'û' | 'ü' => 'u',
        'Ù' | 'Ú' | 'Û' | 'Ü' => 'U',
        'ý' | 'ÿ' => 'y',
        'Ý' => 'Y',
        other => other,
    }
}

/// Whether every character of `text` has a glyph.
pub fn drawable(text: &str) -> bool {
    !text.is_empty() && text.chars().all(|c| glyph(c).is_some())
}

/// Width in console cells of `text` at `scale`.
pub fn width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        return 0;
    }
    (n * (GLYPH_W + GAP) - GAP) * scale
}

/// Height in console cells of one line at `scale` (two pixel rows per cell).
pub fn height(scale: usize) -> usize {
    (GLYPH_H * scale).div_ceil(2)
}

/// The console rows of `text` at `scale`: block characters and spaces, trailing spaces
/// trimmed. `text` must be [`drawable`].
pub fn rows(text: &str, scale: usize) -> Vec<String> {
    let glyphs: Vec<[&str; GLYPH_H]> = text.chars().filter_map(glyph).collect();
    let px_w = width(text, 1);
    let pixel = |x: usize, y: usize| -> bool {
        if y >= GLYPH_H {
            return false;
        }
        let (g, gx) = (x / (GLYPH_W + GAP), x % (GLYPH_W + GAP));
        gx < GLYPH_W && glyphs.get(g).is_some_and(|r| r[y].as_bytes()[gx] == b'#')
    };
    (0..height(scale))
        .map(|row| {
            let (top, bottom) = ((2 * row) / scale, (2 * row + 1) / scale);
            let line: String = (0..px_w * scale)
                .map(|cx| {
                    let x = cx / scale;
                    match (pixel(x, top), pixel(x, bottom)) {
                        (true, true) => '█',
                        (true, false) => '▀',
                        (false, true) => '▄',
                        (false, false) => ' ',
                    }
                })
                .collect();
            line.trim_end().to_owned()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        let all = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,'’-_!?&():+/…";
        for c in all.chars() {
            let g = glyph(c).unwrap_or_else(|| panic!("{c:?}"));
            for r in g {
                assert_eq!(r.len(), GLYPH_W, "{c:?}");
                assert!(r.bytes().all(|b| b == b'#' || b == b'.'), "{c:?}");
            }
            // Only the descender letters (and , _) use the last row.
            if !"gjpqy,_".contains(c) {
                assert_eq!(g[GLYPH_H - 1], ".....", "{c:?}");
            }
        }
        assert!(drawable("Loading Zoë…"));
        assert!(!drawable("Loading 山田"));
        assert!(!drawable(""));
    }

    #[test]
    fn half_blocks_at_each_scale() {
        // "I" at scale 1: rows 0+1 → ".###." over "..#.." = " ▀█▀".
        let r = rows("I", 1);
        assert_eq!(r.len(), 4);
        assert_eq!(r[0], " ▀█▀");
        assert_eq!(r[3], " ▀▀▀");
        assert_eq!(width("HinterOS", 1), 47);
        assert_eq!(width("HinterOS", 2), 94);
        assert_eq!(height(1), 4);
        assert_eq!(height(2), 8);
        assert_eq!(height(3), 12);
        // Scale 2: every pixel is 2 cells wide and one full cell high.
        let r = rows("I", 2);
        assert_eq!(r.len(), 8);
        assert_eq!(r[0], "  ██████");
        assert_eq!(r[1], "    ██");
        for line in rows("Loading Sam…", 3) {
            assert!(line.chars().count() <= width("Loading Sam…", 3));
        }
    }
}
